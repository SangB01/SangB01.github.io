export const standardRewardCards = rewardCards.filter((card) => card.rarity !== 'legendary')

export function createInitialDeck(): CardData[] {
  return initialCardDefinitions.flatMap((card) =>
    Array.from({ length: card.copies ?? 1 }, (_, index) => ({
      ...card,
      id: `${card.id}__${index + 1}`,
    })),
  )
}
